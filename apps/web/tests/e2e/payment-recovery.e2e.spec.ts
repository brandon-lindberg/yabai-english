import { test, expect } from "@playwright/test";
import en from "../../messages/en.json";
import ja from "../../messages/ja.json";
import { readMirrorFixtures, fixtureCommand, signInMirrorUser } from "./helpers/mirror-fixtures";
import { releaseCases, captureRelease } from "./helpers/release-verification";
import { chooseInterfaceLocale, setHeaderTheme } from "./helpers/header-preferences";

test.use({ timezoneId: "America/Los_Angeles" });

for (const scenario of releaseCases()) test(`${scenario.language}: admin reconciles fee recovery and replays a saved Stripe delivery safely`, async ({ page }) => {
  const fixtures = readMirrorFixtures(), admin = fixtures.users.find(user => user.id.endsWith("-payment-admin"))!;
  const learner = fixtures.users.find(user => user.id.endsWith(`-recovery-${scenario.language.toLowerCase()}`))!;
  const data = fixtureCommand("release-payment-recovery", { learnerId: learner.id });
  await page.setViewportSize({ width: scenario.width, height: 950 });
  await signInMirrorUser(page, learner.email, scenario.language);
  for (const [url, number] of [
    [`/api/invoices/${data.invoiceId}/pdf`, data.invoiceNo],
    [`/api/refunds/${data.refundId}/credit-note`, data.creditNoteNo],
  ]) {
    const document = await page.request.get(`${url}?lang=${scenario.locale}`);
    expect(document.ok()).toBe(true);
    expect(document.headers()["content-type"]).toBe("application/pdf");
    expect(document.headers()["content-disposition"]).toContain(number);
    expect((await document.body()).subarray(0, 4).toString()).toBe("%PDF");
  }
  await page.goto(`/en/admin/users/${learner.id}/schedule?date=2025-02-12&view=day`);
  await expect(page).toHaveURL(/\/dashboard/);
  await page.context().clearCookies();
  await signInMirrorUser(page, admin.email, "ENGLISH");
  await expect(page).not.toHaveURL(/\/auth\/signin/);
  await page.goto("/en/admin/payments");
  await page.getByRole("button", { name: /Notifications/ }).click();
  await expect(page.getByTestId("notification-panel")).toBeVisible();
  await page.getByRole("button", { name: /Notifications/ }).click();
  if (scenario.locale === "ja") await chooseInterfaceLocale(page, en.common, "ja");
  const copy = scenario.locale === "ja" ? ja : en, t = copy.admin.refundsPage;
  await setHeaderTheme(page, copy.common, scenario.theme);
  const errors: string[] = [];page.on("pageerror", error => errors.push(error.message));
  const prefix = scenario.locale === "ja" ? "" : "/en";
  const lessons = copy.admin.bookingsPanel;
  const detail = copy.admin.lessonDetail;
  const schedule = copy.admin.lessonCalendar;
  await page.goto(`${prefix}/admin/lessons`);
  await page.getByRole("link", { name: schedule.findPerson }).click();
  const peopleSearch = page.getByPlaceholder(copy.admin.grid.searchPlaceholder);
  await peopleSearch.fill(learner.email);
  await expect(page).toHaveURL(/\?q=/);
  await expect(page.locator("tbody").getByRole("row")).toHaveCount(1);
  await page.getByRole("link").filter({ hasText: "Mirror QA Student" }).and(page.locator(`a[href*="${learner.id}"]`)).click();
  await page.getByRole("link", { name: schedule.open }).click();
  await page.getByLabel(schedule.date).fill("2025-02-12");
  await page.getByRole("button", { name: schedule.jump }).click();
  const cancelledLesson = page.getByRole("link", { name: new RegExp(copy.dashboard.statusCancelled) });
  await expect(cancelledLesson).toContainText(/(?:4:15\s*PM|16:15)/);
  await captureRelease(page, `${scenario.language}-admin-student-schedule`);
  await cancelledLesson.click();
  await expect(page.getByText(data.creditNoteNo, { exact: true })).toBeVisible();
  await page.getByRole("link", { name: schedule.back }).click();
  await expect(page.getByLabel(schedule.date)).toHaveValue("2025-02-12");
  await cancelledLesson.click();
  await page.getByRole("link", { name: schedule.teacherCalendar }).click();
  await expect(page.getByLabel(schedule.date)).toHaveValue("2025-02-12");
  await expect(cancelledLesson).toContainText("Mirror QA Student");
  await page.getByRole("button", { name: copy.dashboard.calendarMonth, exact: true }).click();
  await expect(page).toHaveURL(/view=month/);
  await captureRelease(page, `${scenario.language}-admin-teacher-schedule`);
  await cancelledLesson.click();
  await expect(page.getByText(data.invoiceNo, { exact: true })).toBeVisible();
  await page.goto(`${prefix}/admin/lessons`);
  const search = page.getByRole("searchbox", { name: lessons.searchLabel });
  const apply = page.getByRole("button", { name: lessons.apply });
  await search.fill(learner.email);
  await apply.click();
  await expect(page.getByText(/206/)).toBeVisible();
  await page.getByRole("link", { name: copy.admin.grid.next, exact: true }).click();
  await expect(page).toHaveURL(/page=2/);
  const target = page.locator(`[data-row-id="${data.bookingId}"]`);
  await expect(target).toHaveCount(0);
  await search.fill(data.bookingId);
  await page.getByRole("combobox", { name: lessons.subject }).selectOption(scenario.language);
  await page.getByRole("combobox", { name: lessons.statusLabel }).selectOption("CANCELLED");
  await page.getByLabel(lessons.dateFrom).fill("2025-02-12");
  await page.getByLabel(lessons.dateTo).fill("2025-02-12");
  await apply.click();
  await expect(target).toBeVisible();
  await expect(page).toHaveURL(/zone=America%2FLos_Angeles/);
  await captureRelease(page, `${scenario.language}-admin-lesson-search`);
  await target.getByRole("link").first().click();
  await expect(page.getByText(data.invoiceNo, { exact: true })).toBeVisible();
  await expect(page.getByText(data.creditNoteNo, { exact: true })).toBeVisible();
  await expect(page.getByText(detail.rescheduleStatus.REFUND_REQUESTED, { exact: true })).toBeVisible();
  await expect(page.getByRole("link").filter({ hasText: "Mirror QA Student" })).toHaveAttribute("href", new RegExp(learner.id));
  await captureRelease(page, `${scenario.language}-admin-lesson-detail`);
  await page.getByRole("link", { name: detail.back }).click();
  await expect(search).toHaveValue(data.bookingId);
  await expect(page.getByLabel(lessons.dateFrom)).toHaveValue("2025-02-12");
  await target.getByRole("link").first().click();
  await page.getByRole("link", { name: detail.recoveryLink }).click();
  await expect(page).toHaveURL(new RegExp(`booking=${data.bookingId}`));
  await expect(page.locator("#student-reimbursements")).toContainText(t.reimbursementsEmpty);
  await page.getByRole("link", { name: t.allExceptions }).click();
  const row = page.locator(`#platform-fee-returns [data-row-id="${data.paymentId}"]`);
  await expect(row.getByText(t.statusFeeRecovery, { exact: true })).toBeVisible();
  await row.getByRole("button", { name: t.retryRecovery, exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByText(t.feeRecoveryConfirm, { exact: true })).toBeVisible();
  await captureRelease(page, `${scenario.language}-admin-fee-recovery-confirm`);
  await dialog.getByRole("button", { name: t.keepRecovery, exact: true }).click();
  await row.getByRole("button", { name: t.retryRecovery, exact: true }).click();
  const retry = page.waitForResponse(response => response.url().endsWith("/api/admin/payments/recovery") && response.request().method() === "POST");
  await dialog.getByRole("button", { name: t.confirmRecovery, exact: true }).click();
  const retried = await retry;
  expect(retried.status()).toBe(200);
  expect(retried.request().postDataJSON()).toEqual({ paymentId: data.paymentId, feeOnly: true });
  await expect(row.getByText(t.statusFeeRecovery, { exact: true })).toBeVisible();
  // Stripe credentials are deliberately absent, so this remains a visible queued recovery.
  const event = page.locator(`#stripe-deliveries [data-row-id="${data.eventId}"]`);
  await event.getByRole("button", { name: t.retryEvent, exact: true }).click();
  await expect(dialog.getByText(t.eventConfirm, { exact: true })).toBeVisible();
  await captureRelease(page, `${scenario.language}-admin-webhook-recovery-confirm`);
  await dialog.getByRole("button", { name: t.confirmRecovery, exact: true }).click();
  await expect(event).toHaveCount(0);
  const booking = fixtureCommand("release-status").bookings.find((booking: { id: string }) => booking.id === data.bookingId);
  expect(booking.status).toBe("CANCELLED");expect(booking.payments[0].status).toBe("SUCCEEDED");expect(booking.refunds).toHaveLength(1);
  expect(errors).toEqual([]);
});
