test.runIf(cached)("accounts for all 285 sentences in the first 150 pending N1 nonliteral-match records", async () => {
  const { records, summary } = await loadJapaneseStudyContentReview(process.cwd());
  const n1 = records.filter(row => "written" in row).filter(row => row.introductionLevel === "N1");
  const cohort = n1.filter(row => {
    const selection = row.meaningReview?.examples;
    return selection && [...selection.keep, ...selection.omit].some(decision => decision.reason.startsWith("N1 first nonliteral example cohort:"));
  });
  expect(cohort).toHaveLength(150);
  expect(cohort[0]?.id).toBe("ja-vocabulary:013f46c118");
  expect(cohort.at(-1)?.id).toBe("ja-vocabulary:5d8eead4ba");
  expect(cohort.reduce((sum, row) => sum + (row.meaningReview?.examples?.keep.length ?? 0), 0)).toBe(213);
  expect(cohort.reduce((sum, row) => sum + (row.meaningReview?.examples?.omit.length ?? 0), 0)).toBe(72);
  expect(n1.filter(row => row.meaningReview?.reason.startsWith("N1 first nonliteral example cohort:"))).toHaveLength(82);
  expect(summary.counts).toMatchObject({ units: 10291, sourceRecords: 10307, meaningsWithExactEvidence: 14686, reviewedEquivalentMeanings: 2526, meaningsToReview: 6, constructionMeanings: 0, phraseAttestedMeanings: 6, reviewedPhraseExampleRecords: 2, selectedPhraseExamples: 1, omittedPhraseExamples: 1 });
  expect(summary.publicationChanged).toBe(false);
}, 30_000);


